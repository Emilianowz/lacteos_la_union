-- Lácteos La Unión
-- Esquema inicial de datos. Ejecutar en el SQL Editor del proyecto Supabase.
-- Los pedidos web públicos deberán ingresarse mediante una Edge Function
-- (nunca exponer la clave service_role en index.html).

create extension if not exists pgcrypto;

do $$ begin
  create type public.user_role as enum ('admin', 'seller');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.order_status as enum (
    'pedido_tomado',
    'pedido_preparado',
    'pedido_entregado'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.order_source as enum ('web', 'app');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.product_sale_mode as enum (
    'unit',
    'weight',
    'portion',
    'sliced'
  );
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role public.user_role not null default 'seller',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  sku text unique,
  category_id uuid references public.categories(id) on delete restrict,
  name text not null,
  description text not null default '',
  sale_mode public.product_sale_mode not null default 'unit',
  unit_label text not null default 'unidad',
  price numeric(14,2) not null default 0 check (price >= 0),
  price_per_kg numeric(14,2) check (price_per_kg is null or price_per_kg >= 0),
  price_per_100g numeric(14,2) check (price_per_100g is null or price_per_100g >= 0),
  selection_config jsonb not null default '{}'::jsonb,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null,
  email text,
  address text,
  notes text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists customers_phone_idx on public.customers(phone);
create index if not exists customers_created_by_idx on public.customers(created_by);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  delivery_type text not null default 'retiro'
    check (delivery_type in ('retiro', 'envio')),
  delivery_address text,
  payment_method text,
  source public.order_source not null,
  status public.order_status not null default 'pedido_tomado',
  subtotal numeric(14,2) not null default 0,
  delivery_fee numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  notes text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_created_by_idx on public.orders(created_by);
create index if not exists orders_status_created_at_idx on public.orders(status, created_at desc);
create index if not exists orders_customer_idx on public.orders(customer_id);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name_snapshot text not null,
  sale_mode_snapshot public.product_sale_mode not null,
  unit_label_snapshot text not null,
  quantity numeric(14,3) not null default 1 check (quantity > 0),
  unit_price_snapshot numeric(14,2),
  line_total numeric(14,2),
  selection_details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists order_items_product_idx on public.order_items(product_id);

create table if not exists public.order_status_history (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  previous_status public.order_status,
  new_status public.order_status not null,
  changed_by uuid references public.profiles(id) on delete set null,
  changed_at timestamptz not null default now(),
  note text not null default ''
);

create index if not exists order_status_history_order_idx
  on public.order_status_history(order_id, changed_at desc);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  t text;
begin
  foreach t in array array['profiles','categories','products','customers','orders'] loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format(
      'create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      t
    );
  end loop;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    'seller'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
      and active = true
  );
$$;

create or replace function public.can_access_order(target_order_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_admin() or exists (
    select 1
    from public.orders
    where id = target_order_id
      and created_by = auth.uid()
  );
$$;

