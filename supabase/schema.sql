-- Perfiles: cada usuario ve el suyo; el administrador ve todos.
drop policy if exists "profiles_read_own_or_admin" on public.profiles;
create policy "profiles_read_own_or_admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_admin_manage" on public.profiles;
create policy "profiles_admin_manage" on public.profiles
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Catálogo público de solo lectura; únicamente el administrador lo modifica.
drop policy if exists "categories_read_active" on public.categories;
create policy "categories_read_active" on public.categories
  for select to anon, authenticated
  using (active = true or public.is_admin());

drop policy if exists "categories_admin_manage" on public.categories;
create policy "categories_admin_manage" on public.categories
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "products_read_active" on public.products;
create policy "products_read_active" on public.products
  for select to anon, authenticated
  using (active = true or public.is_admin());

drop policy if exists "products_admin_manage" on public.products;
create policy "products_admin_manage" on public.products
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Clientes: el vendedor accede a los que registró; el administrador a todos.
drop policy if exists "customers_read_own_or_admin" on public.customers;
create policy "customers_read_own_or_admin" on public.customers
  for select to authenticated
  using (created_by = auth.uid() or public.is_admin());

drop policy if exists "customers_seller_create" on public.customers;
create policy "customers_seller_create" on public.customers
  for insert to authenticated
  with check (created_by = auth.uid() or public.is_admin());

drop policy if exists "customers_admin_update" on public.customers;
create policy "customers_admin_update" on public.customers
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Pedidos: vendedores solo consultan los propios; solo administrador cambia estados.
drop policy if exists "orders_read_own_or_admin" on public.orders;
create policy "orders_read_own_or_admin" on public.orders
  for select to authenticated
  using (created_by = auth.uid() or public.is_admin());

drop policy if exists "orders_seller_create" on public.orders;
create policy "orders_seller_create" on public.orders
  for insert to authenticated
  with check (
    (created_by = auth.uid() and status = 'pedido_tomado' and source = 'app')
    or (public.is_admin())
  );

drop policy if exists "orders_admin_update" on public.orders;
create policy "orders_admin_update" on public.orders
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- No se habilita borrado de pedidos ni de sus artículos para conservar historial.
drop policy if exists "order_items_read_accessible_order" on public.order_items;
create policy "order_items_read_accessible_order" on public.order_items
  for select to authenticated
  using (public.can_access_order(order_id));

drop policy if exists "order_items_create_accessible_order" on public.order_items;
create policy "order_items_create_accessible_order" on public.order_items
  for insert to authenticated
  with check (public.can_access_order(order_id));

drop policy if exists "order_status_history_read_accessible_order" on public.order_status_history;
create policy "order_status_history_read_accessible_order" on public.order_status_history
  for select to authenticated
  using (public.can_access_order(order_id));

drop policy if exists "order_status_history_admin_insert" on public.order_status_history;
create policy "order_status_history_admin_insert" on public.order_status_history
  for insert to authenticated
  with check (public.is_admin());

drop policy if exists "app_settings_admin_only" on public.app_settings;
create policy "app_settings_admin_only" on public.app_settings
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

